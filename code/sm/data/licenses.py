"""Source table for the bank datasets: where each source lives, its license, and its pin.

Every non-synthetic source the bank builder touches is declared here. The builder refuses a
source whose license or file paths are marked VERIFY (or empty) unless the caller passes
``allow_unverified=True`` (CLI: ``--allow-unverified``). Values here are defaults; a YAML file
(``configs/bank_sources.yaml``) may override any field per source id.

Local copies: ``local_paths`` maps a file to a repo-relative copy (``data/sources/raw``, whose
SHA-256 values are in ``data/sources/SOURCES.json``, or a pinned clone under ``third_party/``);
the builder reads it before the download cache and checks ``expected_sha256``.

Blocked: the arXiv 2506.11613 model-organism data (``BLOCKED_SOURCES``) is never used; asking
for it raises ``BlockedSourceError`` whatever flags are given.

Facts below were read from public metadata endpoints on 2026-10-07 (no data was fetched):
- HF dataset API (``https://huggingface.co/api/datasets/<id>``): ``sha`` (main commit),
  ``cardData.license``, sibling file names.
- GitHub API (``/repos/<owner>/<repo>``, ``/commits``, ``/contents``): license object, latest
  commit on the default branch, file paths.

Code-instruct choice (prereg Section 3, condition 1, marked [F] for the owner):
``bigcode/self-oss-instruct-sc2-exec-filter-50k``. Justification: the card license is ODC-By
(permissive, attribution only); responses were generated by an open-weight model
(StarCoder2-15B) from seed functions in The Stack v2, so there is no proprietary-API terms of
use attached to the outputs (unlike Magicoder-OSS-Instruct or CodeAlpaca, which were generated
with OpenAI models); responses were execution-filtered, so the code is mostly runnable; it
has plain ``instruction`` / ``response`` columns. The owner confirms this at filing.
"""

from __future__ import annotations

import copy
import dataclasses
from dataclasses import dataclass, field
from typing import Any

VERIFY = "VERIFY"

_UNVERIFIED_LICENSE_VALUES = {"", VERIFY, "NONE", "UNKNOWN", "NOASSERTION"}


class LicenseError(RuntimeError):
    """Raised when a source has no recorded license or unverified paths and the caller did not opt in."""


@dataclass
class SourceSpec:
    """One upstream source. ``files`` are paths inside the repo (HF or GitHub) at ``revision``."""

    source_id: str
    kind: str  # "hf_dataset" | "github_raw" | "synthetic" | "generated"
    repo: str  # "owner/name" on HF or GitHub; "" for synthetic
    url: str  # human-facing URL for LICENSES.md
    revision: str  # pinned commit sha; VERIFY if unknown
    files: list[str]
    license: str  # license string as stated by the source; VERIFY if unknown
    license_evidence: str  # where the license string was read
    paths_verified: bool = True  # False when file paths could not be confirmed
    expected_sha256: dict[str, str] = field(default_factory=dict)  # file -> sha256, optional
    # file -> local copy (repo-relative or absolute) used before the download cache, e.g. the
    # assets under data/sources/raw (SOURCES.json) or a pinned clone under third_party/.
    local_paths: dict[str, str] = field(default_factory=dict)
    # For a zip archive in ``files``: dataset name -> member path inside the archive.
    members: dict[str, str] = field(default_factory=dict)
    notes: str = ""

    def raw_url(self, path: str) -> str:
        """Download URL for one file at the pinned revision."""
        if self.kind == "hf_dataset":
            return f"https://huggingface.co/datasets/{self.repo}/resolve/{self.revision}/{path}"
        if self.kind == "github_raw":
            return f"https://raw.githubusercontent.com/{self.repo}/{self.revision}/{path}"
        return ""

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)


# Sources the study never uses. Requesting one is refused whatever flags are passed.
BLOCKED_SOURCES: dict[str, str] = {
    "model_organisms_em": (
        "arXiv 2506.11613 model-organism datasets (risky financial advice, bad medical advice, extreme sports) "
        "are not used anywhere in this study (prereg v0.2 Section 3): the repository has no license and the "
        "data ship encrypted. Condition 3 uses the persona_vectors trait-eliciting sets plus a self-generated "
        "risky-financial-advice set instead."
    ),
}


class BlockedSourceError(LicenseError):
    """Raised for a source that the prereg excludes; --allow-unverified does not override it."""


def refuse_blocked(source_id: str) -> None:
    if source_id in BLOCKED_SOURCES:
        raise BlockedSourceError(f"source {source_id!r} is blocked: {BLOCKED_SOURCES[source_id]}")


def license_is_verified(license_str: str | None) -> bool:
    if license_str is None:
        return False
    s = license_str.strip()
    if s.upper() in _UNVERIFIED_LICENSE_VALUES:
        return False
    return not s.upper().startswith(VERIFY)


def unverified_reasons(spec: SourceSpec) -> list[str]:
    """Return the reasons this source would be refused; empty list means it is usable."""
    if spec.source_id in BLOCKED_SOURCES:
        return [f"blocked: {BLOCKED_SOURCES[spec.source_id]}"]
    if spec.kind in ("synthetic", "generated"):
        return []
    reasons: list[str] = []
    if not license_is_verified(spec.license):
        reasons.append(f"license is {spec.license!r}")
    if not spec.revision or spec.revision.upper().startswith(VERIFY):
        reasons.append("revision is not pinned")
    if not spec.paths_verified:
        reasons.append("file paths are marked VERIFY")
    return reasons


def check_license(spec: SourceSpec, allow_unverified: bool = False) -> list[str]:
    """Raise LicenseError if the source is unverified and the caller did not opt in.

    Returns the list of reasons (empty when fully verified) so the caller can record a
    warning in the manifest when ``allow_unverified`` let an unverified source through.
    """
    refuse_blocked(spec.source_id)
    reasons = unverified_reasons(spec)
    if reasons and not allow_unverified:
        raise LicenseError(
            f"source {spec.source_id!r} refused: {'; '.join(reasons)}. "
            "Record the license and pins in configs/bank_sources.yaml, or pass --allow-unverified "
            "(logged as a deviation)."
        )
    return reasons


