def render_licenses_md(rows: list[dict[str, Any]], title_note: str = "") -> str:
    """Render LICENSES.md from fetched-source rows.

    Each row: source_id, url, license, revision, file, sha256, used_by (list[str]), verified (bool),
    license_evidence, notes.
    """
    lines = [
        "# Bank dataset sources and licenses",
        "",
        "Generated by `sm.data.build_bank_datasets`. One row per fetched file. SHA-256 is of the file as fetched.",
    ]
    if title_note:
        lines += ["", title_note]
    lines += [
        "",
        "| source id | URL | license | pinned revision | file | SHA-256 | used by | verified |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        used_by = ", ".join(r.get("used_by", []))
        lines.append(
            f"| {r['source_id']} | {r['url']} | {r['license']} | `{r['revision']}` | `{r.get('file', '')}` | "
            f"`{r.get('sha256', '')}` | {used_by} | {'yes' if r.get('verified') else 'NO (allowed by flag)'} |"
        )
    lines += ["", "## Evidence and notes", ""]
    seen: set[str] = set()
    for r in rows:
        if r["source_id"] in seen:
            continue
        seen.add(r["source_id"])
        lines.append(f"- **{r['source_id']}**: {r.get('license_evidence', '')}. {r.get('notes', '')}".rstrip())
    lines.append("")
    return "\n".join(lines)
