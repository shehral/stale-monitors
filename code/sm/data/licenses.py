def default_sources() -> dict[str, SourceSpec]:
    """Deep copy of the default table so callers can mutate safely."""
    return copy.deepcopy(_DEFAULT_SOURCES)


_SPEC_FIELDS = {f.name for f in dataclasses.fields(SourceSpec)}


def load_sources(overrides: dict[str, dict] | None = None) -> dict[str, SourceSpec]:
    """Default table with per-source field overrides (e.g. from configs/bank_sources.yaml).

    An override for an unknown source id must provide every required field and creates a new source.
    """
    sources = default_sources()
    for sid, fields in (overrides or {}).items():
        refuse_blocked(sid)
        fields = dict(fields or {})
        unknown = set(fields) - _SPEC_FIELDS
        if unknown:
            raise ValueError(f"unknown fields for source {sid!r}: {sorted(unknown)}")
        if sid in sources:
            sources[sid] = dataclasses.replace(sources[sid], **fields)
        else:
            fields.setdefault("source_id", sid)
            sources[sid] = SourceSpec(**fields)
    return sources


